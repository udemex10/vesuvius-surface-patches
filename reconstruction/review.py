"""Verify, inspect or reproduce the ten global-coordinate interior mesh exports."""

import argparse
import hashlib
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys
import zipfile

import numpy as np
import tifffile

ROOT = Path(__file__).resolve().parent


def digest(path):
    with path.open("rb") as stream:
        return hashlib.file_digest(stream, "sha256").hexdigest()


def load_chart(root, case):
    return np.stack([tifffile.imread(root / case["mesh"] / (axis + ".tif")) for axis in "xyz"], axis=-1)


def inspect_chart(chart, pitch, selected=None):
    g = chart.astype("f8")
    valid = np.isfinite(g).all(-1) & (g >= 0).all(-1)
    usable = valid[:-1, :-1] & valid[:-1, 1:] & valid[1:, 1:] & valid[1:, :-1]
    if selected is not None:
        if selected.dtype != np.bool_ or selected.shape != usable.shape or np.any(selected & ~usable):
            raise ValueError("A qualified face lies outside valid four-corner mesh support")
        usable &= selected
    a, b, c, d = (corners[usable] for corners in (g[:-1, :-1], g[:-1, 1:], g[1:, 1:], g[1:, :-1]))
    area2 = np.linalg.norm(np.cross(b - a, c - a), axis=1) + np.linalg.norm(np.cross(c - a, d - a), axis=1)
    return {"quad_count": int(usable.sum()), "triangulated_cm2": float(area2.sum() * .5 * (pitch / 10000) ** 2),
            "native_xyz_bounds": [g[valid].min(0).tolist(), g[valid].max(0).tolist()]}


def verify(root=ROOT):
    listed = {}
    for line in (root / "SHA256SUMS").read_text(encoding="utf-8").splitlines():
        checksum, name = line.split("  ", 1)
        path = (root / name).resolve()
        if name in listed or not path.is_relative_to(root) or digest(path) != checksum:
            raise ValueError(f"Payload checksum mismatch at {name}")
        listed[name] = checksum
    # Bytecode caches can be generated by the reviewer's Python process.
    actual = {p.relative_to(root).as_posix() for p in root.rglob("*") if p.is_file()
              and p != root / "SHA256SUMS" and "__pycache__" not in p.parts}
    if actual != set(listed):
        raise ValueError(f"Unlisted or missing payload paths: {actual ^ set(listed)}")
    manifest = json.loads((root / "index.json").read_text())
    total = 0.
    corroborated = 0.
    evidence = json.loads((root / "curve-faces/bracketed_geometry.json").read_text())
    for case in manifest["cases"]:
        chart = load_chart(root, case)
        result = inspect_chart(chart, case["pitch_um"])
        if abs(result["triangulated_cm2"] - case["archive_triangulated_cm2"]) > 1e-8:
            raise ValueError(f"Area differs from archived geometry in {case['id']}")
        if result["quad_count"] != case["quad_count"] or case["native_xyz_bounds"] != result["native_xyz_bounds"]:
            raise ValueError(f"Geometry differs from the manifest in {case['id']}")
        total += result["triangulated_cm2"]
        if case["family"] == "extension":
            name=case["id"].removeprefix("PHerc0125_")
            record=evidence["cases"][name]
            with np.load(root / "curve-faces" / (name+"_faces.npz")) as face:
                section=inspect_chart(chart,case["pitch_um"],face["qualified_quads"])
                if section["quad_count"] != record["qualifying_faces"] or abs(section["triangulated_cm2"]-record["bracketed_native_area_cm2"]) > 1e-8:
                    raise ValueError(f"Qualified face count or area mismatch for {name}")
                corroborated+=section["triangulated_cm2"]
                if name=="east":
                    secondary=face["also_inside_stock_agreement_quads"]
                    if np.any(secondary & ~face["qualified_quads"]) or abs(inspect_chart(chart,case["pitch_um"],secondary)["triangulated_cm2"]-record["also_bracketed_and_stock_agreement_cm2"])>1e-8:
                        raise ValueError("East curve-and-stock subset differs")
        print(f"{case['id']:22s} {result['triangulated_cm2']:.6f} cm²")
    if len(manifest["cases"]) != 10 or round(total, 6) != 4.258803:
        raise ValueError("Unexpected mesh count or combined area")
    if round(corroborated,6)!=0.813130:
        raise ValueError("Unexpected corroborated extension area")
    with zipfile.ZipFile(root/"benchmark/growpatch-comparison-source.zip") as z:
        sums = {line.split("  ",1)[1]:line.split("  ",1)[0] for line in z.read("SHA256SUMS").decode().splitlines()}
        if set(sums)!=set(z.namelist())-{"SHA256SUMS"} or any(hashlib.sha256(z.read(p)).hexdigest()!=h for p,h in sums.items()):
            raise ValueError("Benchmark companion integrity failure")
    print(f"{len(listed)} checksums matched, {len(sums)} nested checksums matched, 10 interior meshes, "
          f"{total:.6f} cm² total, {corroborated:.6f} cm² curve-corroborated.")


def render(case, work):
    # Use the original sampler and its normal convention for both scan geometries.
    os.environ["CROSS_SECTIONS_WORK"] = str(work)
    os.environ["FIRST_LETTERS_GRID_CASE"] = "PHerc0268_inner" if case["specimen"] == "PHerc0268" else "PHerc0125"
    sys.path.insert(0, str(ROOT / "original/src"))
    from first_letters_native_sample import sample_native
    from PIL import Image
    g = load_chart(ROOT, case)
    nr, nc = g.shape[:2]
    row, col = np.mgrid[:(nr - 1)*8, :(nc - 1)*8]
    i, j = row // 8, col // 8
    v, u = (row % 8)[..., None] / 8, (col % 8)[..., None] / 8
    a, b, c, d = (g[i + y, j + x] for y, x in ((0, 0), (0, 1), (1, 0), (1, 1)))
    good = (np.minimum.reduce([a, b, c, d]) >= 0).all(-1)
    p = (1-v)*((1-u)*a+u*b) + v*((1-u)*c+u*d)
    n = np.cross((1-v)*(b-a)+v*(d-c), (1-u)*(c-a)+u*(d-b))
    length = np.linalg.norm(n, axis=2)
    good &= length > .5
    n /= np.maximum(length[..., None], 1e-8)
    dest = work / "renders" / case["id"]
    sample_native(dest, case["native_volume_url"], p, n, good, case["pitch_um"], {"field": case["id"]})
    for name, expected in (("ct17.npy", case["ct17_sha256"]), ("mask.npy", case["mask_sha256"])):
        if digest(dest / name) != expected:
            raise ValueError(f"Public source reconstruction differs at {case['id']} {name}")
    image = np.load(dest / "ct17.npy", mmap_mode="r")[8]
    mask = np.load(dest / "mask.npy")
    lo, hi = np.percentile(image[mask], (1, 99))
    view = np.uint8(np.clip((image.astype(float)-lo)/max(hi-lo,1),0,1)*255)
    Image.fromarray(np.where(mask, view, 0)).save(dest / "center.png")
    print(f"Rebuilt and verified all 17 planes and the mask; center preview: {dest / 'center.png'}")


def command(script, *args, cwd=None):
    subprocess.run([sys.executable, str(script), *map(str, args)], check=True, cwd=cwd or ROOT)


def rebuild(cases, selected, work):
    groups = {"original", "extensions", "all"}
    if selected not in groups and selected not in {c["id"] for c in cases}:
        raise ValueError(f"Unknown case {selected}")
    originals = [c for c in cases if c["family"] == "original"]
    extensions = [c for c in cases if c["family"] == "extension"]
    if selected in ("all", "original"):
        requested = originals
    else:
        requested = [c for c in originals if c["id"] == selected]
    need_extensions = selected in ("all", "extensions") or any(c["id"] == selected for c in extensions)
    if need_extensions and not any(c["id"] == "PHerc0125_y3310" for c in requested):
        requested = [next(c for c in originals if c["id"] == "PHerc0125_y3310"), *requested]
    for case in requested:
        command(ROOT / "original/cross_sections.py", "reproduce", "--case", case["id"], "--work-dir", work / "original")
    if not need_extensions:
        return
    active = work / "extensions"
    shutil.copytree(ROOT / "extensions/scripts", active / "scripts", dirs_exist_ok=True)
    (active / "data/cache").mkdir(parents=True, exist_ok=True)
    initial = Path("results/first_letters_deep/PHerc0125_y3310/geometry_nodes.npz")
    (active / initial).parent.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(work / "original" / initial, active / initial)
    wanted = [c for c in extensions if selected in ("all", "extensions") or c["id"] == selected]
    for direction in sorted({c["direction"] for c in wanted}):
        if direction == "east":
            command("scripts/growbench_recover_unread.py", "--threads", "2", cwd=active)
            command("scripts/growbench_recover_unread.py", "--combine", cwd=active)
            command("scripts/growbench_recover_unread_export.py", cwd=active)
        else:
            command("scripts/growbench_recover_unread_directions.py", direction, cwd=active)
        command("scripts/growbench_recover_unread_components.py", direction, cwd=active)
    for case in wanted:
        directory = active / "results/growbench/recover" / ("pherc125_" + ("extension" if case["direction"] == "east" else case["direction"]))
        flat = directory / ("flat" if case["component"] == 1 else f"flat_{case['component']}")
        mesh = flat / Path(case["mesh"]).name
        for axis in "xyz":
            name = axis + ".tif"
            if digest(mesh / name) != digest(ROOT / case["mesh"] / name):
                raise ValueError(f"Source rebuild differs at {case['id']} {name}")
        for name, expected in (("ct17.npy", case["ct17_sha256"]), ("mask.npy", case["mask_sha256"])):
            if digest(flat / name) != expected:
                raise ValueError(f"Source rebuild differs at {case['id']} {name}")
        print("Source-built geometry, CT and mask verified:", case["id"])


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    sub=parser.add_subparsers(dest="action",required=True)
    sub.add_parser("verify")
    for name in ("render","rebuild"):
        p=sub.add_parser(name)
        p.add_argument("case", help="Case ID in index.json; rebuild also accepts original, extensions, all.")
        p.add_argument("--work",type=Path,required=True)
    args=parser.parse_args()
    if args.action=="verify":
        verify()
        return
    work=args.work.resolve()
    if work==ROOT or ROOT in work.parents:
        parser.error("Use a working directory outside the read-only extracted release.")
    cases=json.loads((ROOT/"index.json").read_text())["cases"]
    if args.action=="rebuild":
        rebuild(cases,args.case,work)
    else:
        matches=[c for c in cases if c["id"]==args.case]
        if not matches:parser.error("Select one case ID from index.json.")
        render(matches[0],work)


if __name__=="__main__":
    main()
